//! Per-service pages of the documentation book.

use std::collections::BTreeMap;
use std::path::Path;

use serde_json::Value;

const SERVICES_SRC: &str = "crates/mercurio/src/services";
const FIXTURES: &str = "crates/mercurio/tests/fixtures/services";
const SNAPSHOTS: &str = "crates/mercurio/tests/snapshots/services";
const OUT: &str = "docs/book/src/services";
const SUMMARY_IN: &str = "docs/book/SUMMARY.in.md";
const SUMMARY: &str = "docs/book/src/SUMMARY.md";
const PAGE_HEADER: &str = "<!-- Generated by cargo xtask docs; edit the sources it names, not this file. -->";
const SUMMARY_HEADER: &str = "<!-- Generated by cargo xtask docs from docs/book/SUMMARY.in.md. -->\n";
const INDEX_HEADER: &str = "<!-- Generated by cargo xtask docs. -->";
const BEGIN: &str = "<!-- services:begin (generated by cargo xtask docs) -->";
const END: &str = "<!-- services:end -->";
const MAX_EXAMPLES: usize = 8;
const MAX_REJECTED: usize = 4;

type Fixture = (String, Value, BTreeMap<String, Flags>);

/// `valid` and `ok` of one case in an insta snapshot.
#[derive(Debug, Default, Clone, Copy)]
struct Flags {
    valid: Option<bool>,
    ok: Option<bool>,
}

pub(crate) fn generate(root: &Path, services: Value) -> Result<(), String> {
    let Value::Array(mut services) = services else {
        return Err("mercurio services --json: expected an array".to_owned());
    };
    services.sort_by_key(|s| str_of(s, "name").to_lowercase());
    let features: BTreeMap<String, String> =
        services.iter().map(|s| (str_of(s, "id").to_owned(), service_feature(str_of(s, "id")))).collect();

    let mut warnings = Vec::new();
    let mut files = BTreeMap::new();
    for svc in &services {
        let page = page(root, svc, &features, &mut warnings)?;
        files.insert(format!("{OUT}/{}.md", str_of(svc, "id")), page);
    }
    files.insert(format!("{OUT}/index.md"), index_page(&services, &features));

    let summary = read(&root.join(SUMMARY_IN))?;
    let Some((head, tail)) = summary.split_once(BEGIN).and_then(|(head, rest)| Some((head, rest.split_once(END)?.1)))
    else {
        return Err(format!("{SUMMARY_IN}: markers {BEGIN:?} ... {END:?} not found"));
    };
    let mut block = vec![BEGIN.to_owned(), "- [Services](services/index.md)".to_owned()];
    for s in &services {
        block.push(format!("  - [{}](services/{}.md)", str_of(s, "name"), str_of(s, "id")));
    }
    block.push(END.to_owned());
    let summary = format!("{SUMMARY_HEADER}{head}{}{tail}", block.join("\n"));
    files.insert(SUMMARY.to_owned(), summary);

    let out = root.join(OUT);
    if out.exists() {
        std::fs::remove_dir_all(&out).map_err(|e| format!("{OUT}: {e}"))?;
    }
    std::fs::create_dir_all(&out).map_err(|e| format!("{OUT}: {e}"))?;
    for (path, content) in &files {
        std::fs::write(root.join(path), content).map_err(|e| format!("{path}: {e}"))?;
    }
    for w in &warnings {
        eprintln!("warning: {w}");
    }
    eprintln!("{} service pages written", services.len());
    if warnings.is_empty() {
        Ok(())
    } else {
        Err("services with differences but no `# Differences with Apprise` module docs".to_owned())
    }
}

fn read(path: &Path) -> Result<String, String> {
    std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))
}

fn str_of<'a>(v: &'a Value, key: &str) -> &'a str {
    v.get(key).and_then(Value::as_str).unwrap_or("")
}

fn strs<'a>(v: &'a Value, key: &str) -> Vec<&'a str> {
    v.get(key).and_then(Value::as_array).map_or_else(Vec::new, |a| a.iter().filter_map(Value::as_str).collect())
}

fn int_of(v: &Value, key: &str) -> u64 {
    v.get(key).and_then(Value::as_u64).unwrap_or(0)
}

/// Whether an optional JSON value carries something: present, not null, not `false`, not zero and not an empty string, array or object.
fn is_set(v: Option<&Value>) -> bool {
    match v {
        None | Some(Value::Null) => false,
        Some(Value::Bool(b)) => *b,
        Some(Value::Number(n)) => n.as_f64() != Some(0.0),
        Some(Value::String(s)) => !s.is_empty(),
        Some(Value::Array(a)) => !a.is_empty(),
        Some(Value::Object(o)) => !o.is_empty(),
    }
}

/// Same rule as `service_feature` in `crates/mercurio/build.rs`.
fn service_feature(id: &str) -> String {
    format!("service-{id}")
}

/// Rust files of a service module: `<id>.rs` or every file under `<id>/`.
fn module_files(root: &Path, sid: &str) -> Vec<String> {
    let single = format!("{SERVICES_SRC}/{sid}.rs");
    if root.join(&single).exists() {
        return vec![single];
    }
    let mut out = Vec::new();
    walk_rs(root, &format!("{SERVICES_SRC}/{sid}"), &mut out);
    out.sort();
    out
}

fn walk_rs(root: &Path, dir: &str, out: &mut Vec<String>) {
    let Ok(entries) = std::fs::read_dir(root.join(dir)) else { return };
    for entry in entries.flatten() {
        let name = entry.file_name().to_string_lossy().into_owned();
        let path = format!("{dir}/{name}");
        if name.starts_with('.') {
            continue;
        }
        if entry.file_type().is_ok_and(|t| t.is_dir()) {
            walk_rs(root, &path, out);
        } else if name.ends_with(".rs") {
            out.push(path);
        }
    }
}

/// The `//!` header of a module as Markdown (intra-doc links made plain).
fn module_doc(root: &Path, path: &str) -> String {
    let source = std::fs::read_to_string(root.join(path)).unwrap_or_default();
    let mut lines = Vec::new();
    for line in source.lines() {
        if let Some(rest) = line.strip_prefix("//!") {
            lines.push(rest.strip_prefix(' ').unwrap_or(rest));
        } else if !lines.is_empty() || !line.trim().is_empty() {
            break;
        }
    }
    let text = lines.join("\n");
    plain_code_links(&plain_code_links(text.trim(), true), false)
}

/// `` [`x`](target) `` (with `link`) or `` [`x`] `` becomes `` `x` ``.
pub(crate) fn plain_code_links(text: &str, link: bool) -> String {
    let mut out = String::new();
    let mut rest = text;
    while let Some((before, after)) = rest.split_once("[`") {
        out.push_str(before);
        let found = after
            .split_once(['`', ']'])
            .filter(|(word, _)| !word.is_empty())
            .and_then(|(word, _)| Some((word, after.get(word.len()..)?.strip_prefix("`]")?)))
            .and_then(|(word, tail)| match link {
                true => Some((word, tail.strip_prefix('(')?.split_once(')')?.1)),
                false => Some((word, tail)),
            });
        if let Some((word, tail)) = found {
            out.push_str(&format!("`{word}`"));
            rest = tail;
        } else {
            out.push_str("[`");
            rest = after;
        }
    }
    out.push_str(rest);
    out
}

/// Module docs sit under a `##` heading: push their headings below it.
fn demote(markdown: &str) -> String {
    let mut fenced = false;
    let mut out = Vec::new();
    for line in markdown.split('\n') {
        let text = line.trim_start_matches('#');
        if line.starts_with("```") {
            fenced = !fenced;
        } else if !fenced && (1..=3).contains(&(line.len() - text.len())) && text.starts_with(' ') {
            out.push(format!("### {}", text.trim()));
            continue;
        }
        out.push(line.to_owned());
    }
    out.join("\n")
}

fn fixtures_for(root: &Path, sid: &str) -> Result<Vec<Fixture>, String> {
    let mut names: Vec<String> = std::fs::read_dir(root.join(FIXTURES))
        .map_err(|e| format!("{FIXTURES}: {e}"))?
        .flatten()
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|n| *n == format!("{sid}.json") || (n.starts_with(&format!("{sid}__")) && n.ends_with(".json")))
        .collect();
    names.sort();
    names
        .into_iter()
        .map(|name| {
            let fixture =
                serde_json::from_str(&read(&root.join(FIXTURES).join(&name))?).map_err(|e| format!("{name}: {e}"))?;
            let snap = root.join(SNAPSHOTS).join(format!("{}.snap", name.trim_end_matches(".json")));
            let results = snapshot_results(&std::fs::read_to_string(snap).unwrap_or_default());
            Ok((name, fixture, results))
        })
        .collect()
}

/// `valid` and `ok` of every case in an insta snapshot (YAML keyed by case name), read line by line.
fn snapshot_results(snapshot: &str) -> BTreeMap<String, Flags> {
    let mut results = BTreeMap::new();
    let mut case: Option<String> = None;
    for line in snapshot.lines() {
        let mut chars = line.chars();
        let first = chars.next().filter(|c| !c.is_whitespace() && *c != '#' && *c != '-');
        if let Some(first) = first
            && let Some((key, _)) = chars.as_str().split_once(':').filter(|(_, value)| value.trim().is_empty())
        {
            let name = format!("{first}{key}").trim().trim_matches('"').to_owned();
            results.insert(name.clone(), Flags::default());
            case = Some(name);
            continue;
        }
        let Some(flag) = line.strip_prefix("  ") else { continue };
        let (key, value) = flag.split_once(": ").unwrap_or_default();
        let value = match value.trim_end() {
            "true" => true,
            "false" => false,
            _ => continue,
        };
        if let Some(flags) = case.as_ref().and_then(|c| results.get_mut(c)) {
            match key {
                "valid" => flags.valid = Some(value),
                "ok" => flags.ok = Some(value),
                _ => {}
            }
        }
    }
    results
}

fn md_escape(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

fn code(text: &str) -> String {
    if text.contains('`') { format!("`` {text} ``") } else { format!("`{text}`") }
}

fn codes<S: AsRef<str>>(items: impl IntoIterator<Item = S>) -> String {
    items.into_iter().map(|i| code(i.as_ref())).collect::<Vec<_>>().join(", ")
}

fn yes_no(flag: bool) -> &'static str {
    if flag { "yes" } else { "no" }
}

fn limit(n: u64, unit: &str) -> String {
    if n == 0 {
        return "unlimited".to_owned();
    }
    let digits = n.to_string();
    let mut grouped = String::new();
    for (i, c) in digits.chars().enumerate() {
        if i > 0 && (digits.len() - i).is_multiple_of(3) {
            grouped.push(',');
        }
        grouped.push(c);
    }
    format!("{grouped} {unit}")
}

fn scheme_list(svc: &Value) -> String {
    codes(strs(svc, "schemes").iter().map(|s| format!("{s}://")))
}

fn fmt_type(p: &Value) -> String {
    let ty = str_of(p, "type");
    let bound = |k| p.get(k).filter(|v| !v.is_null()).map(Value::to_string);
    match (bound("min"), bound("max")) {
        (Some(lo), Some(hi)) => format!("{ty}, {lo} to {hi}"),
        (Some(lo), None) => format!("{ty}, min {lo}"),
        (None, Some(hi)) => format!("{ty}, max {hi}"),
        (None, None) => ty.to_owned(),
    }
}

fn notes(p: &Value) -> String {
    let mut out = Vec::new();
    if is_set(p.get("aliases")) {
        out.push(format!("also {}", codes(strs(p, "aliases"))));
    }
    if is_set(p.get("secret")) {
        out.push("secret".to_owned());
    }
    if is_set(p.get("prefix")) {
        out.push(format!("prefix {}", code(str_of(p, "prefix"))));
    }
    if is_set(p.get("group")) {
        out.push(format!("any of {}", codes(strs(p, "group"))));
    }
    if is_set(p.get("delim")) {
        let delims: Vec<String> = str_of(p, "delim")
            .chars()
            .map(|d| if d == ' ' { "space".to_owned() } else { code(&d.to_string()) })
            .collect();
        out.push(format!("separated by {}", delims.join(" or ")));
    }
    if is_set(p.get("pattern")) {
        out.push(format!("must match {}", code(str_of(p, "pattern"))));
    }
    if is_set(p.get("values")) {
        let values = strs(p, "values");
        let listed = if values.len() > 12 {
            format!("{}, ... ({} values)", codes(&values[..12]), values.len())
        } else {
            codes(&values)
        };
        out.push(format!("one of {listed}"));
    }
    if is_set(p.get("ignored")) {
        out.push("accepted, no effect".to_owned());
    }
    if is_set(p.get("note")) {
        out.push(str_of(p, "note").to_owned());
    }
    md_escape(&out.join("; "))
}

fn overview(svc: &Value, features: &BTreeMap<String, String>) -> String {
    let id = str_of(svc, "id");
    let title = int_of(svc, "title_maxlen");
    let throttle = int_of(svc, "throttle_ms");
    let rows = [
        ("Schemes", scheme_list(svc)),
        ("Cargo feature", features.get(id).map_or_else(|| "none (always compiled)".to_owned(), |f| code(f))),
        (
            "Service",
            if is_set(svc.get("service_url")) { format!("<{}>", str_of(svc, "service_url")) } else { String::new() },
        ),
        ("Body formats", format!("{} (first is the default)", codes(strs(svc, "formats")))),
        ("Attachments", yes_no(is_set(svc.get("attachments"))).to_owned()),
        (
            "Title length",
            if title == 0 { "no title (merged into the body)".to_owned() } else { limit(title, "characters") },
        ),
        ("Body length", limit(int_of(svc, "body_maxlen"), "characters")),
        ("Body lines", limit(int_of(svc, "body_max_line_count"), "lines")),
        ("Request throttle", if throttle == 0 { "none".to_owned() } else { format!("{throttle} ms between requests") }),
        ("Vendor URLs accepted", yes_no(is_set(svc.get("native_url"))).to_owned()),
    ];
    let mut out = vec!["| | |".to_owned(), "|---|---|".to_owned()];
    out.extend(rows.iter().filter(|(_, v)| !v.is_empty()).map(|(k, v)| format!("| {k} | {v} |")));
    out.join("\n")
}

fn url_formats(svc: &Value) -> String {
    let templates = strs(svc, "templates");
    if templates.is_empty() {
        return String::new();
    }
    let note = if templates.iter().any(|t| t.contains("{schema}")) {
        format!("\n`{{schema}}` is one of {}.\n", scheme_list(svc))
    } else {
        String::new()
    };
    format!("## URL formats\n\n```text\n{}\n```\n{note}", templates.join("\n"))
}

fn params<'a>(svc: &'a Value, key: &str) -> &'a [Value] {
    svc.get(key).and_then(Value::as_array).map_or(&[], Vec::as_slice)
}

fn default_of(p: &Value) -> String {
    match (is_set(p.get("default")), is_set(p.get("inferred"))) {
        (true, true) => format!("{} (usually; depends on the URL)", code(str_of(p, "default"))),
        (true, false) => code(str_of(p, "default")),
        (false, _) => String::new(),
    }
}

fn tokens_table(svc: &Value) -> String {
    let rows: Vec<String> = params(svc, "tokens")
        .iter()
        .map(|p| {
            format!(
                "| {} | {} | {} | {} | {} | {} |",
                code(&format!("{{{}}}", str_of(p, "key"))),
                md_escape(str_of(p, "name")),
                fmt_type(p),
                yes_no(is_set(p.get("required"))),
                default_of(p),
                notes(p)
            )
        })
        .collect();
    if rows.is_empty() {
        return String::new();
    }
    let head = "## URL tokens\n\n| Token | Meaning | Type | Required | Default | Notes |\n|---|---|---|---|---|---|\n";
    format!("{head}{}\n", rows.join("\n"))
}

fn params_table(svc: &Value) -> String {
    let tokens: BTreeMap<&str, &Value> = params(svc, "tokens").iter().map(|t| (str_of(t, "key"), t)).collect();
    let (mut rows, mut prefixed) = (Vec::new(), Vec::new());
    for p in params(svc, "params") {
        if is_set(p.get("prefix")) {
            prefixed.push(format!(
                "- {}: {}",
                code(&format!("{}name=value", str_of(p, "prefix"))),
                md_escape(str_of(p, "name"))
            ));
        } else if is_set(p.get("sets")) {
            let sets = strs(p, "sets");
            let first = sets.first().and_then(|s| tokens.get(s));
            let (name, ty) =
                first.map_or_else(|| (String::new(), String::new()), |t| (md_escape(str_of(t, "name")), fmt_type(t)));
            let sets_note = format!("sets {}", codes(sets.iter().map(|t| format!("{{{t}}}"))));
            let note = [sets_note, notes(p)].into_iter().filter(|x| !x.is_empty()).collect::<Vec<_>>().join("; ");
            rows.push(format!("| {} | {name} | {ty} | | {note} |", code(str_of(p, "key"))));
        } else {
            rows.push(format!(
                "| {} | {} | {} | {} | {} |",
                code(str_of(p, "key")),
                md_escape(str_of(p, "name")),
                fmt_type(p),
                default_of(p),
                notes(p)
            ));
        }
    }
    let mut out = vec!["## Query parameters".to_owned(), String::new()];
    if rows.is_empty() {
        out.extend(["No service-specific parameters.".to_owned(), String::new()]);
    } else {
        out.extend(["| Parameter | Meaning | Type | Default | Notes |".to_owned(), "|---|---|---|---|---|".to_owned()]);
        out.append(&mut rows);
        out.push(String::new());
    }
    if !prefixed.is_empty() {
        out.extend(["Prefixed parameters:".to_owned(), String::new()]);
        out.append(&mut prefixed);
        out.push(String::new());
    }
    let common: Vec<&str> = mercurio::service::COMMON_PARAMS.iter().map(|p| p.key).collect();
    out.push(format!("The [common URL parameters](../url-parameters.md) ({}) apply as well.", codes(common)));
    out.join("\n") + "\n"
}

/// Scheme, path depth, user info and query keys: one example per shape.
fn url_shape(url: &str) -> (String, usize, bool, Vec<String>) {
    let (scheme, rest) = url.split_once("://").unwrap_or((url, ""));
    let (path, query) = rest.split_once('?').unwrap_or((rest, ""));
    let mut keys: Vec<String> = query
        .split('&')
        .filter(|k| !k.is_empty())
        .map(|k| k.split('=').next().unwrap_or_default().to_owned())
        .collect();
    keys.sort();
    (scheme.to_owned(), path.matches('/').count(), path.contains('@'), keys)
}

fn examples_section(fixtures: &[Fixture]) -> String {
    let (mut good, mut shapes, mut bad) = (Vec::<String>::new(), Vec::new(), Vec::<String>::new());
    for (_, fixture, results) in fixtures {
        for case in params(fixture, "cases") {
            let url = str_of(case, "url");
            let result =
                case.get("name").and_then(Value::as_str).and_then(|n| results.get(n)).copied().unwrap_or_default();
            let empty = result.valid.is_none() && result.ok.is_none();
            if url.is_empty() || url.contains("{FIXTURES}") || url.chars().count() > 160 || empty {
                continue;
            }
            if result.valid != Some(false) && result.ok == Some(true) {
                let shape = url_shape(url);
                if !shapes.contains(&shape) && !good.iter().any(|u| u == url) {
                    shapes.push(shape);
                    good.push(url.to_owned());
                }
            } else if result.valid == Some(false) && !bad.iter().any(|u| u == url) && url.contains("://") {
                bad.push(url.to_owned());
            }
        }
    }
    good.sort_by_key(|u| (u.split('?').nth(1).map_or(0, |q| q.chars().count()), u.chars().count()));
    good.truncate(MAX_EXAMPLES);
    bad.truncate(MAX_REJECTED);
    if good.is_empty() && bad.is_empty() {
        return String::new();
    }
    let mut out = vec!["## Examples".to_owned(), String::new()];
    if !good.is_empty() {
        out.extend(["Accepted URLs (tokens are fake):".to_owned(), String::new(), "```text".to_owned()]);
        out.extend(good.iter().cloned());
        out.extend(["```".to_owned(), String::new()]);
    }
    if !bad.is_empty() {
        out.extend(["Rejected URLs:".to_owned(), String::new(), "```text".to_owned()]);
        out.extend(bad.iter().cloned());
        out.extend(["```".to_owned(), String::new()]);
    }
    if let Some(first) = good.first() {
        out.extend(["Send one from the command line:".to_owned(), String::new(), "```sh".to_owned()]);
        out.push(format!("mercurio -t 'Backup' -b 'Finished in 42s' '{first}'"));
        out.extend(["```".to_owned(), String::new()]);
    }
    out.join("\n")
}

fn split_differences(doc: &str) -> (&str, &str) {
    match doc.split_once("\n# Differences with Apprise\n") {
        Some((notes, diff)) => (notes.trim_end(), diff.trim()),
        None => (doc, ""),
    }
}

fn check_differences(sid: &str, fixtures: &[Fixture], notes: &str, diff: &str, warnings: &mut Vec<String>) {
    if !diff.is_empty() {
        return;
    }
    let missing = "but its module docs have no `# Differences with Apprise` section";
    let diverges = |v: &Value| is_set(v.get("divergence"));
    if fixtures.iter().any(|(_, f, _)| diverges(f) || params(f, "cases").iter().any(diverges)) {
        warnings.push(format!("{sid}: fixture `divergence` note, {missing}"));
    }
    if fixtures.iter().any(|(_, f, _)| is_set(f.get("source"))) {
        warnings.push(format!("{sid}: `source` fixture, {missing}"));
    }
    if notes.contains("ivergen") {
        warnings.push(format!("{sid}: module docs mention a divergence, {missing}"));
    }
}

fn page(
    root: &Path,
    svc: &Value,
    features: &BTreeMap<String, String>,
    warnings: &mut Vec<String>,
) -> Result<String, String> {
    let sid = str_of(svc, "id");
    let own = module_files(root, sid);
    let fixtures = fixtures_for(root, sid)?;
    let mut parts = vec![
        format!("# {}", str_of(svc, "name")),
        String::new(),
        PAGE_HEADER.to_owned(),
        String::new(),
        overview(svc, features),
        String::new(),
    ];
    for section in [url_formats(svc), tokens_table(svc), params_table(svc), examples_section(&fixtures)] {
        if !section.is_empty() {
            parts.extend([section.trim_end().to_owned(), String::new()]);
        }
    }
    let doc = own.first().map(|path| module_doc(root, path)).unwrap_or_default();
    let (notes, diff) = split_differences(&doc);
    check_differences(sid, &fixtures, notes, diff, warnings);
    if !notes.is_empty() {
        parts.extend(["## Notes", ""].map(str::to_owned));
        parts.extend([demote(notes), String::new()]);
    }
    if !diff.is_empty() {
        parts.extend(["## Differences with Apprise".to_owned(), String::new(), demote(diff), String::new()]);
    }
    Ok(parts.join("\n"))
}

/// The table of [`mercurio::service::COMMON_PARAMS`], for `url-parameters.md`.
pub(crate) fn common_params_table() -> String {
    let mut out =
        vec!["| Parameter | Meaning | Type | Default | Notes |".to_owned(), "|---|---|---|---|---|".to_owned()];
    for p in mercurio::service::COMMON_PARAMS.iter().map(mercurio::service::Param::to_json) {
        out.push(format!(
            "| {} | {} | {} | {} | {} |",
            code(str_of(&p, "key")),
            md_escape(str_of(&p, "name")),
            fmt_type(&p),
            default_of(&p),
            notes(&p)
        ));
    }
    out.join("\n") + "\n"
}

fn index_page(services: &[Value], features: &BTreeMap<String, String>) -> String {
    let mut out = vec![
        "# Services".to_owned(),
        String::new(),
        INDEX_HEADER.to_owned(),
        String::new(),
        format!(
            "{} services. Each page lists the URL formats, every query parameter with its default, known differences with Apprise \
             and examples.",
            services.len()
        ),
        String::new(),
        "Every service is compiled by default (`all-services`). Each has its own Cargo feature (the Feature column): \
         with `default-features = false`, turn on only the ones you use. Matrix end-to-end encryption is `service-matrix-e2ee`."
            .to_owned(),
        String::new(),
        "| Service | Schemes | Attachments | Formats | Feature |".to_owned(),
        "|---|---|---|---|---|".to_owned(),
    ];
    for svc in services {
        let id = str_of(svc, "id");
        out.push(format!(
            "| [{}]({id}.md) | {} | {} | {} | {} |",
            md_escape(str_of(svc, "name")),
            scheme_list(svc),
            yes_no(is_set(svc.get("attachments"))),
            strs(svc, "formats").join(", "),
            features.get(id).map(|f| code(f)).unwrap_or_default()
        ));
    }
    out.join("\n") + "\n"
}
